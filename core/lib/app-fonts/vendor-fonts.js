// Fetches the web fonts the template apps (Books, Gallery, Music, Shop, Games, Musicpod) use, so they are served from this tree and
// not from a font service on every page view. Run it by hand when the list below changes:
//   node core/lib/app-fonts/vendor-fonts.js
// It writes, next to this file, one folder per family (the .woff2 files and the family's licence text), and core/styles/app-fonts.css,
// the one stylesheet that declares them. Commit what it writes. Nothing here runs in the browser.
// Only the "latin" and "latin-ext" scripts are kept: a title in another script falls back to the system font, as it did when a
// family had no glyph for it. Every family below is under the SIL Open Font License; the licence text is fetched with the files.
// The weights are the union of what the apps ask for; a variable family is fetched as a range and is one file per script.
'use strict';
const fs = require('fs');
const path = require('path');
const https = require('https');

// family (as the font service names it) -> [css2 axis spec, licence folder in the fonts repository]
const FAMILIES = [
  ['Playfair Display', 'wght@700', 'ofl/playfairdisplay'],
  ['Spectral', 'wght@400;600', 'ofl/spectral'],
  ['Inter', 'wght@400;500;600;700', 'ofl/inter'],
  ['Caprasimo', 'wght@400', 'ofl/caprasimo'],
  ['Figtree', 'wght@400;500;600;700', 'ofl/figtree'],
  ['Fraunces', 'opsz,wght@9..144,400..700', 'ofl/fraunces'],
  ['Work Sans', 'wght@400;500;600', 'ofl/worksans'],
  ['Space Grotesk', 'wght@400;500;600', 'ofl/spacegrotesk'],
  ['IBM Plex Sans', 'wght@400;500;600', 'ofl/ibmplexsans'],
  ['Bricolage Grotesque', 'opsz,wght@12..96,500..800', 'ofl/bricolagegrotesque'],
  ['DM Sans', 'wght@400;500;600', 'ofl/dmsans'],
  ['DM Mono', 'wght@400', 'ofl/dmmono'],
  ['Poppins', 'wght@400;600;700', 'ofl/poppins'],
  ['Roboto Mono', 'wght@400;500', 'ofl/robotomono'],
];
const SCRIPTS = ['latin', 'latin-ext'];
// the service gives each browser the files that browser can use: ask as a current one, which is given woff2
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const HERE = __dirname;
const STYLES = path.join(HERE, '..', '..', 'styles', 'app-fonts.css');

function get(url) {
  return new Promise((res, rej) => {
    https.get(url, { headers: { 'User-Agent': UA } }, (r) => {
      if (r.statusCode >= 300 && r.statusCode < 400 && r.headers.location) return res(get(new URL(r.headers.location, url).toString()));
      if (r.statusCode !== 200) { r.resume(); return rej(new Error('HTTP ' + r.statusCode + ' ' + url)); }
      const chunks = [];
      r.on('data', (c) => chunks.push(c));
      r.on('end', () => res(Buffer.concat(chunks)));
    }).on('error', rej);
  });
}
const slug = (f) => f.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

(async () => {
  const query = FAMILIES.map(([f, spec]) => 'family=' + f.replace(/ /g, '+') + ':' + spec).join('&') + '&display=swap';
  const css = (await get('https://fonts.googleapis.com/css2?' + query)).toString('utf8');
  const blocks = css.split(/\/\* ([a-z-]+) \*\/\s*/).slice(1);      // [script, rule, script, rule, ...]
  const out = [
    '/*',
    ' * Fonts of the template apps (Books, Gallery, Music, Shop, Games, Musicpod), served from this tree.',
    ' * Generated by core/lib/app-fonts/vendor-fonts.js: do not edit by hand. Every family is under the SIL Open Font License; the',
    ' * licence text of each is in core/lib/app-fonts/<family>/. Only the latin and latin-ext scripts are kept.',
    ' */',
  ];
  const have = new Set();
  let kept = 0, bytes = 0;
  for (let i = 0; i < blocks.length; i += 2) {
    const script = blocks[i], rule = blocks[i + 1];
    if (SCRIPTS.indexOf(script) < 0) continue;
    const family = /font-family:\s*'([^']+)'/.exec(rule)[1];
    const url = /src:\s*url\(([^)]+)\)/.exec(rule)[1];
    const dir = path.join(HERE, slug(family));
    fs.mkdirSync(dir, { recursive: true });
    const file = path.basename(new URL(url).pathname);
    const local = slug(family) + '/' + file;
    if (!have.has(local)) {
      const buf = await get(url);
      if (buf.slice(0, 4).toString('latin1') !== 'wOF2') throw new Error('not a woff2 file: ' + url);
      fs.writeFileSync(path.join(HERE, local), buf);
      have.add(local); bytes += buf.length;
    }
    out.push('/* ' + script + ' */', rule.replace(/url\([^)]+\)/, "url('../lib/app-fonts/" + local + "')").trim());
    kept++;
  }
  for (const [family, , repoDir] of FAMILIES) {
    let text = null;
    for (const name of ['OFL.txt', 'LICENSE.txt']) {
      try { text = await get('https://raw.githubusercontent.com/google/fonts/main/' + repoDir + '/' + name); break; } catch (e) { /* try the next name */ }
    }
    if (!text) throw new Error('no licence text found for ' + family + ' (' + repoDir + ')');
    fs.mkdirSync(path.join(HERE, slug(family)), { recursive: true });
    fs.writeFileSync(path.join(HERE, slug(family), 'LICENSE.txt'), text);
  }
  fs.writeFileSync(STYLES, out.join('\n') + '\n');
  console.log('wrote ' + kept + ' @font-face rules, ' + have.size + ' files, ' + Math.round(bytes / 1024) + ' KB, ' + FAMILIES.length + ' licences');
})().catch((e) => { console.error(e.message); process.exit(1); });
